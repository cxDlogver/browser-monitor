import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const directory=dirname(fileURLToPath(import.meta.url));
const metadataResponse=await fetch('https://registry.npmjs.org/@cxdlogver%2Fbrowser-monitor-cli',{headers:{Accept:'application/json'}});
if(!metadataResponse.ok)throw Error('Anonymous metadata status '+metadataResponse.status);
const metadata=await metadataResponse.json();
const pkg=metadata.versions['0.1.0'];
if(!pkg)throw Error('Published version missing');
const tarResponse=await fetch(pkg.dist.tarball);
if(!tarResponse.ok)throw Error('Anonymous tarball status '+tarResponse.status);
const archive=Buffer.from(await tarResponse.arrayBuffer());
const integrity='sha512-'+createHash('sha512').update(archive).digest('base64');
const packed=JSON.parse(await readFile(directory+'/pack-manifest.json','utf8'));
if(integrity!==packed.integrity||integrity!==pkg.dist.integrity)throw Error('Tarball differs from tested artifact');
const report={status:'passed',source:'anonymous HTTPS requests to official npm registry',metadataHttpStatus:metadataResponse.status,tarballHttpStatus:tarResponse.status,name:pkg.name,version:pkg.version,latest:metadata['dist-tags'].latest,registry:'https://registry.npmjs.org/',tarball:pkg.dist.tarball,fileCount:pkg.dist.fileCount,downloadedBytes:archive.length,testedIntegrity:packed.integrity,registryIntegrity:pkg.dist.integrity,observedDownloadIntegrity:integrity,integrityMatches:true,bin:pkg.bin,engines:pkg.engines,checkedAt:new Date().toISOString()};
await writeFile(directory+'/registry-verification.json',JSON.stringify(report,null,2)+'\n');
await writeFile(directory+'/registry-download.tgz',archive);
console.log(JSON.stringify(report,null,2));
